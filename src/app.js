//////////////////////////////////////////////////////
// app.js
//////////////////////////////////////////////////////
import express from "express";
import cors from "cors";
import morgan from "morgan";
import helmet from "helmet";

///////////////////////////////////////////////////////////

import indexRoutes from "./routes/index.routes.js";
import bitrixRoutes from "./routes/bitrix.routes.js";
import clientesRoutes from "./routes/clientes.routes.js";

///////////////////////////////////////////////////////////

////////////////////////////////////////////////////////////
// INICIALIZACIÓN DE EXPRESS
////////////////////////////////////////////////////////////

const app = express();

////////////////////////////////////////////////////////////
// CORS
////////////////////////////////////////////////////////////

app.use(
    cors({
        origin: "*",
        methods: ["GET", "POST", "PUT", "DELETE"],
        allowedHeaders: ["Content-Type", "Authorization"]
    })
);

///////////////////////////////////////////////////////////
// MIDDLEWARES
///////////////////////////////////////////////////////////

app.use(helmet());

///////////////////////////////////////////////////////////
// BODY PARSER
///////////////////////////////////////////////////////////

app.use(
    express.json({
        limit: "10mb"
    })
);

app.use(
    express.urlencoded({
        extended: true,
        limit: "10mb"
    })
);

////////////////////////////////////////////////////////////
// LOGGER HTTP
////////////////////////////////////////////////////////////

app.use(
    morgan("dev")
);

////////////////////////////////////////////////////////////
// CONFIGURACIÓN GLOBAL
////////////////////////////////////////////////////////////

app.disable("x-powered-by");

////////////////////////////////////////////////////////////
// RUTA PRINCIPAL
////////////////////////////////////////////////////////////

app.get("/", (req, res) => {

    return res.status(200).json({
        success: true,
        message: "🚀 API REST funcionando correctamente",
        timestamp: new Date().toISOString()
    });

});

///////////////////////////////////////////////////////////
// WEBHOOK RUTAS
///////////////////////////////////////////////////////////

app.use("/api", indexRoutes);

app.use("/webhook", bitrixRoutes);

app.use("/clientes", clientesRoutes);

////////////////////////////////////////////////////////////
// ERROR 404 - MANEJO DE RUTAS NO ENCONTRADAS
////////////////////////////////////////////////////////////

app.use((req, res) => {

    return res.status(404).json({
        success: false,
        error: "ENDPOINT_NOT_FOUND",
        message: `La ruta ${req.originalUrl} no existe`
    });

});

///////////////////////////////////////////////////////////
// HEALTH CHECK
///////////////////////////////////////////////////////////

app.get("/api/health", (req, res) => {

    res.status(200).json({
        success: true,
        message: "Servidor funcionando"
    });
});

///////////////////////////////////////////////////////////
// PRUEBA DE RUTAS
///////////////////////////////////////////////////////////
app.get("/webhook/test", (req, res) => {

    res.json({
        success: true,
        message: "Webhook registrado y funcionando correctamente"
    });

});

////////////////////////////////////////////////////////////
// MANEJO GLOBAL DE ERRORES
////////////////////////////////////////////////////////////

app.use((error, req, res, next) => {

    console.error("❌ ERROR GLOBAL:", error);

    return res.status(error.status || 500).json({
        success: false,
        error: error.code || "INTERNAL_SERVER_ERROR",
        message:
            process.env.NODE_ENV === "production"
                ? "Error interno del servidor"
                : error.message
    });

});

////////////////////////////////////////////////////////////
// EXPORTAR APP
////////////////////////////////////////////////////////////
export default app;

