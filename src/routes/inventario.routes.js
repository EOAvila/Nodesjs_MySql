// inventario.routes.js
/////////////////////////////////////////////////////////////

import express from "express";

import {

    obtenerInventarioController,

    listarInventarioController,

    registrarEntradaController,

    registrarSalidaController,

    ajustarInventarioController,

    listarMovimientosController,

    sincronizarInventarioController

} from "../controllers/inventario.controller.js";

const router =
    express.Router();

/////////////////////////////////////////////////////////////
// INVENTARIO
/////////////////////////////////////////////////////////////

router.get(
    "/",
    listarInventarioController
);

router.get(
    "/:producto_id",
    obtenerInventarioController
);

/////////////////////////////////////////////////////////////
// MOVIMIENTOS
/////////////////////////////////////////////////////////////

router.get(
    "/movimientos/lista",
    listarMovimientosController
);

/////////////////////////////////////////////////////////////
// ENTRADAS
/////////////////////////////////////////////////////////////

router.post(
    "/entrada",
    registrarEntradaController
);

/////////////////////////////////////////////////////////////
// SALIDAS
/////////////////////////////////////////////////////////////

router.post(
    "/salida",
    registrarSalidaController
);

/////////////////////////////////////////////////////////////
// AJUSTES
/////////////////////////////////////////////////////////////

router.post(
    "/ajuste",
    ajustarInventarioController
);

/////////////////////////////////////////////////////////////
// SINCRONIZACIÓN
/////////////////////////////////////////////////////////////

router.post(
    "/sincronizar",
    sincronizarInventarioController
);

export default router;